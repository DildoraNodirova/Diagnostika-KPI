def seed():

    db = SessionLocal()

    try:

        created_sections = 0
        updated_sections = 0

        created_indicators = 0
        updated_indicators = 0

        for section_data in SECTIONS:

            # --------------------------------------------
            # SECTION
            # --------------------------------------------

            section = (
                db.query(KPISection)
                .filter(KPISection.number == section_data["number"])
                .first()
            )

            if section:

                section.name = section_data["name"]
                section.weight = 60

                updated_sections += 1

            else:

                section = KPISection(
                    number=section_data["number"],
                    name=section_data["name"],
                    weight=60,
                )

                db.add(section)
                db.flush()

                created_sections += 1


            # --------------------------------------------
            # INDICATORS
            # --------------------------------------------

            for indicator_name, unit, weight in section_data["indicators"]:

                indicator = (
                    db.query(KPIIndicator)
                    .filter(
                        KPIIndicator.section_id == section.id,
                        KPIIndicator.name == indicator_name
                    )
                    .first()
                )

                if indicator:

                    indicator.unit = unit or None
                    indicator.weight = weight

                    updated_indicators += 1

                else:

                    indicator = KPIIndicator(
                        section_id=section.id,
                        name=indicator_name,
                        unit=unit or None,
                        plan=0,
                        weight=weight,
                    )

                    db.add(indicator)

                    created_indicators += 1


        db.commit()

        print()
        print("=" * 60)
        print("KPI SEED MUVAFFAQIYATLI YAKUNLANDI")
        print("=" * 60)
        print(f"Yangi bo'limlar:       {created_sections}")
        print(f"Yangilangan bo'limlar: {updated_sections}")
        print(f"Yangi KPI lar:         {created_indicators}")
        print(f"Yangilangan KPI lar:   {updated_indicators}")
        print(f"Jami bo'limlar:        {len(SECTIONS)}")
        print("=" * 60)

    except Exception as e:

        db.rollback()

        print("XATOLIK:")
        print(e)

    finally:

        db.close()


if __name__ == "__main__":
    seed()