def fix_sections():
    db = SessionLocal()

    try:
        updated = 0

        for number, name in SECTION_NAMES.items():

            section = (
                db.query(KPISection)
                .filter(KPISection.number == number)
                .first()
            )

            if section:
                old_name = section.name
                section.name = name

                print(
                    f"{number}: "
                    f"{old_name}  ->  {name}"
                )

                updated += 1

        # 34 va 35 noto'g'ri sectionlar
        extra_sections = (
            db.query(KPISection)
            .filter(KPISection.number > 33)
            .all()
        )

        print()
        print("33 dan ortiq sectionlar:")

        for section in extra_sections:
            print(
                section.id,
                "|",
                section.number,
                "|",
                section.name
            )

        db.commit()

        print()
        print("=" * 60)
        print("SECTION NOMLARI YANGILANDI")
        print("=" * 60)
        print("Yangilangan:", updated)

    except Exception as e:
        db.rollback()
        print("XATOLIK:", e)
        raise

    finally:
        db.close()


if __name__ == "__main__":
    fix_sections()